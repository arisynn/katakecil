import assert from 'node:assert/strict';
import {ReaderSegmentWindow} from '../src/utils/readerSegmentWindow.ts';
const calls=[];
const cache=new ReaderSegmentWindow(async(ep,part)=>{
 calls.push(`${ep}:${part}`);
 await new Promise(r=>setTimeout(r,5));
 return {episodeNumber:ep,part,content:'contoh teks'};
},3);
assert.equal(cache.peek(1,0),undefined);
cache.prefetch(1,0);
const a=await cache.get(1,0);
assert.deepEqual(a,{episodeNumber:1,part:0,content:'contoh teks'});
assert.equal(calls.length,1,'prefetch and navigation should share one network request');
assert.equal(cache.peek(1,0),a);
cache.prefetch(1,1);
await cache.get(1,1);
await cache.get(1,2);
assert.equal(cache.cachedParts,3);
await cache.get(1,3);
assert.equal(cache.cachedParts,3,'RAM cache must remain bounded');
assert.equal(cache.peek(1,0),undefined,'old parts must be evicted');
let attempts=0;
const failure=new ReaderSegmentWindow(async()=>{attempts++;if(attempts===1)throw Error('network');return 'ok';});
failure.prefetch(5,0);
await new Promise(r=>setTimeout(r,8));
assert.equal(await failure.get(5,0),'ok');
assert.equal(attempts,2,'failed prefetch must be retriable');
cache.clear();assert.equal(cache.cachedParts,0);
console.log('PASS: cache only holds 3 segments, navigations reuse prefetched chunks, failed prefetch retries.');
