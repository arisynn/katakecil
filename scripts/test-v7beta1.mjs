import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
const read = file => readFileSync(file, 'utf8');
const pkg = JSON.parse(read('package.json'));
assert.equal(pkg.version, '7.0.0-beta.1');
const app = read('src/App.tsx');
const publicUI = read('src/pages/PublicLibrary.tsx');
const secure = read('src/SecureReaderApp.tsx');
const notices = read('src/features/public/components/DiscoveryNotices.tsx');
const announcements = read('src/data/announcements.ts');
const css = read('src/design/v70-beta1.css');
assert.match(app, /design\/v70-beta1\.css/);
assert.match(publicUI, /newestReadingProgress\(published, episodes, readProgress\)/);
assert.match(publicUI, /Lanjutkan Membaca/);
assert.match(publicUI, /onClick=\{\(\)=>navigate\(`\/baca\/\$\{continuation.slug\}`\)\}/);
assert.match(publicUI, /to=\{`\/baca\/\$\{book.slug\}`\}/);
assert.doesNotMatch(publicUI, /\/baca\/\$\{continuation.slug\}\?episode=/);
assert.match(publicUI, /readerHeading\(ep.title, ep.episode_number\)/);
assert.match(secure, /updatedAt:Date\.now\(\)/);
assert.match(notices, /event.key === 'ArrowRight'/);
assert.match(announcements, /ends_at\.is\.null,ends_at\.gt/);
assert.match(css, /--kk-border: var\(--sapphire-border\)/);
assert.match(css, /\.kk-v7-notice-dots button::after/);
assert.doesNotMatch(css.replace(/\/\*[\s\S]*?\*\//g, ''), /#[\da-f]{3,8}\b|\brgba?\s*\(|\bhsla?\s*\(/i);
const transpile = (file) => ts.transpileModule(read(file), { fileName: file, compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext, jsx: ts.JsxEmit.ReactJSX }, reportDiagnostics: true });
for (const file of ['src/utils/readingProgress.ts','src/pages/PublicLibrary.tsx','src/SecureReaderApp.tsx','src/features/public/components/DiscoveryNotices.tsx','src/data/announcements.ts']) {
  assert.equal(transpile(file).diagnostics?.filter(x => x.category === ts.DiagnosticCategory.Error).length ?? 0, 0, file);
}
const module = await import(`data:text/javascript;base64,${Buffer.from(transpile('src/utils/readingProgress.ts').outputText).toString('base64')}`);
const { parseReadingProgress: parse, newestReadingProgress: newest } = module;
assert.equal(parse(null), null);
assert.equal(parse({ ep: -1, offset: 0 }), null);
assert.equal(parse({ ep: 1.5, offset: 0 }), null);
assert.equal(parse({ ep: 2, part: 1, offset: 0 }), null);
assert.equal(parse({ ep: 0, offset: 0 }).ep, 0);
assert.equal(parse({ ep: 5, part: 0, offset: 42 }).updatedAt, null);
assert.equal(parse({ ep: 5, part: 0, offset: 42, updatedAt: 400 }).updatedAt, 400);
const books = [{id:'old'}, {id:'new'}, {id:'not-released'}];
const episodes = [{book_id:'old',episode_number:0}, {book_id:'new',episode_number:2}];
const progress = {old:parse({ep:0,offset:0}), new:parse({ep:2,offset:12,updatedAt:100}), 'not-released':parse({ep:99,offset:0,updatedAt:1000})};
assert.equal(newest(books, episodes, book => progress[book.id]).book.id, 'new');
assert.equal(newest([books[0]], episodes, book => progress[book.id]).progress.ep, 0);
assert.equal(newest([books[2]], episodes, book => progress[book.id]), null);
console.log('PASS V7 Beta.1: Sapphire alias repair, readable responsive states, latest progress, resume CTA, announcement filtering and accessible controls.');
