import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
const read = file => readFileSync(file, 'utf8');
const publicPage = read('src/pages/PublicLibrary.tsx');
const header = read('src/components/public/PublicHeader.tsx');
const styles = read('src/design/public-experience.css');
const app = read('src/App.tsx');
const pkg = JSON.parse(read('package.json'));
assert.equal(pkg.version, '7.1.0-rc.1');
assert.match(app, /design\/public-experience\.css/);
assert.match(publicPage, /const retry = \(\) =>/);
assert.match(publicPage, /onClick=\{retry\}/);
assert.match(publicPage, /Katalog belum bisa dimuat/);
assert.match(publicPage, /error && path !== '\/tentang'/);
assert.match(publicPage, /getPublicUpcomingChapters\(\)\.catch\(\(\) => \[\]\)/);
assert.match(publicPage, /getPublicAnnouncements\(\)\.catch\(\(\) => \[\]\)/);
assert.match(publicPage, /'Berlangsung','Tamat','Jeda'/);
assert.match(publicPage, /setSort\('terbaru'\)/);
assert.match(publicPage, /kk-v71-results-meta/);
assert.match(publicPage, /kk-v71-resume-link/);
assert.match(publicPage, /onClick=\{\(\)=>navigate\(`\/baca\/\$\{book.slug\}`\)\}/);
assert.doesNotMatch(publicPage, /\/baca\/\$\{book.slug\}\?episode=\$\{progress/);
assert.match(publicPage, /ep\.episode_number === 0 \? 'P'/);
assert.match(header, /kk-v71-owner-entry/);
assert.match(header, /menuTrigger\.current\?\.focus\(\)/);
assert.match(styles, /var\(--kk-primary\)/);
assert.doesNotMatch(styles.replace(/\/\*[\s\S]*?\*\//g, ''), /#[\da-f]{3,8}\b|\brgba?\s*\(/i);
const source = read('src/features/public/storyFilters.ts');
const output = ts.transpileModule(source, {fileName:'storyFilters.ts', reportDiagnostics:true, compilerOptions:{target:ts.ScriptTarget.ES2022, module:ts.ModuleKind.ESNext}});
assert.equal(output.diagnostics?.filter(x=>x.category===ts.DiagnosticCategory.Error).length??0,0);
const {matchesStoryStatus} = await import(`data:text/javascript;base64,${Buffer.from(output.outputText).toString('base64')}`);
for (const state of ['ongoing','completed','hiatus']) assert.equal(matchesStoryStatus(state,'Semua'),true);
assert.equal(matchesStoryStatus('ongoing','Berlangsung'),true);
assert.equal(matchesStoryStatus('hiatus','Berlangsung'),false);
assert.equal(matchesStoryStatus('completed','Berlangsung'),false);
assert.equal(matchesStoryStatus('completed','Tamat'),true);
assert.equal(matchesStoryStatus('hiatus','Jeda'),true);
assert.equal(matchesStoryStatus('ongoing','Jeda'),false);
console.log('PASS V7.1 Public: status semantics, catalog retry, collection resume, owner navigation, Sapphire CSS.');
