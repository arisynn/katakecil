import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { runInNewContext } from 'node:vm';
import ts from 'typescript';
const read = (file) => readFileSync(file, 'utf8');
const pkg = JSON.parse(read('package.json'));
assert.match(pkg.version, /^7\.0\.0-(?:alpha\.4|beta\.[12])$/);
const reader = read('src/SecureReaderApp.tsx');
const controls = read('src/components/ReaderControls.tsx');
const contents = read('src/components/ReaderPanels.tsx');
const loading = read('src/components/ReaderEpisodeLoading.tsx');
const app = read('src/App.tsx');
const css = read('src/design/v70-alpha4.css');
const theme = read('src/utils/theme.ts');
const recovery = read('src/secure-reader.css');
assert.doesNotMatch(recovery, /#[\da-f]{3,8}\b|\brgba?\s*\(/i);
assert.match(recovery, /background:\s*var\(--kk-bg\)/);
const headings = read('src/utils/readerHeading.ts');
assert.match(headings, /Number.isSafeInteger\(episodeNumber\).*>= 0/);
assert.match(app, /design\/v70-alpha4.css/);
assert.match(reader, /completionStorageKey\(bookId\)/);
assert.match(reader, /normalizeCompletedEpisodes/);
assert.match(reader, /toggleCompletedEpisode\(previous,segment.episodeNumber\)/);
assert.match(reader, /completedEpisodeNumbers=\{completedEpisodes\}/);
assert.match(reader, /estimateRemainingMinutes\(chapter.wordCount,pageIndex\+1,pages.length\)/);
assert.match(reader, /episodeNumber=\{loadingEpisodeNumber\}/);
assert.match(controls, /Tandai bab selesai/);
assert.match(controls, /Batalkan tanda selesai/);
assert.match(controls, /estimatedMinutesRemaining/);
assert.match(contents, /completedEpisodeNumbers.includes\(Number\(number\)\)/);
assert.match(loading, /headingMeta\.eyebrow/);
assert.match(loading, /headingMeta\.title/);
assert.doesNotMatch(css.replace(/\/\*[\s\S]*?\*\//g, ''), /#[\da-f]{3,8}\b|\brgba?\s*\(|\bhsla?\s*\(/i);
assert.equal((theme.match(/barBg:'var\(--kk-overlay\)'/g) ?? []).length, 2);
// Domain logic: no manuscript text in persisted completion data.
const utility = read('src/utils/readerCompletion.ts');
assert.doesNotMatch(utility, /content_md|plainText|markdown|manuscript/);
const transpiled = ts.transpileModule(`${utility.replace(/^export /gm, '')}\nthis.api={completionStorageKey,normalizeCompletedEpisodes,toggleCompletedEpisode,estimateRemainingMinutes};`, {
  compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.None }, reportDiagnostics: true,
});
assert.equal(transpiled.diagnostics?.filter(d=>d.category===ts.DiagnosticCategory.Error).length??0, 0);
const sandbox = { Set, Number, Array, Math };
runInNewContext(transpiled.outputText, sandbox);
const api = sandbox.api;
assert.equal(api.completionStorageKey('abc'), 'kk-reader-completed-v1-abc');
assert.deepEqual(Array.from(api.normalizeCompletedEpisodes([3,1,3,-1,0,10000,'2',NaN,2.5])), [0,1,3]);
assert.deepEqual(Array.from(api.normalizeCompletedEpisodes({ content: 'private' })), []);
assert.deepEqual(Array.from(api.toggleCompletedEpisode([2,5],5)), [2]);
assert.deepEqual(Array.from(api.toggleCompletedEpisode([2],4)), [2,4]);
assert.deepEqual(Array.from(api.toggleCompletedEpisode([2],-5)), [2]);
assert.equal(api.estimateRemainingMinutes(2200,1,10), 9);
assert.equal(api.estimateRemainingMinutes(2200,10,10), 0);
assert.equal(api.estimateRemainingMinutes(0,1,10), null);
assert.equal(api.estimateRemainingMinutes(1000,1,0), null);
assert.equal(api.estimateRemainingMinutes(220,1,10), 1);
for (const file of ['src/SecureReaderApp.tsx','src/components/ReaderControls.tsx','src/components/ReaderPanels.tsx','src/components/ReaderEpisodeLoading.tsx','src/utils/readerCompletion.ts','src/utils/theme.ts']) {
  const output = ts.transpileModule(read(file), { fileName:file, reportDiagnostics:true, compilerOptions:{jsx:ts.JsxEmit.ReactJSX,target:ts.ScriptTarget.ES2022} });
  assert.equal(output.diagnostics?.filter(d=>d.category===ts.DiagnosticCategory.Error).length??0, 0, file);
}
console.log('PASS V7 Alpha.4: per-story completion metadata, chapter ETA, title-aware loading, menu/contents wiring, semantic reader overlay, TS/TSX parse.');
